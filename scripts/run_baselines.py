#!/usr/bin/env python3
"""Baseline / confound experiments for the TDA benchmark (additive-only).

Part A — non-topological baselines under the SAME stratified 5-fold CV
         protocol as the 616-config sweep (StratifiedKFold(5, shuffle=True,
         random_state=43) == sweep's random_seed 42 + repetition 1):
   * MNIST 0/1: LogisticRegression + RandomForest on flattened raw pixels (784)
   * ECG200:    LogisticRegression + RandomForest on raw 96-length signals;
                sum-of-squares single feature; amplitude single feature
   * sphere/torus at each noise level: logistic on 3 norm features
                (mean/max/min per-cloud) and on the 300 raw coordinates
   * hand rule: 'cloud contains a point with norm > 1.1 => torus'

Part B — scale-matched synthetic (generated by generate_matched_synthetic.py:
         genus-1 vs genus-2 torus, quantile-matched norm distributions):
   * norm-feature + raw-coordinate logistic baselines (confound check)
   * TDA subset: 2 filtrations x 3 vectorizers x 2 classifiers = 12 configs
     per noise level (sigma = 0.00, 0.30), same 5-fold CV

Part C — measured bottleneck distances (gudhi) between persistence diagrams
         of clean (sigma=0.00) and noisy (sigma=0.15/0.30) sphere/torus clouds,
         vs the paper's bound d_B <= O(sigma sqrt(log n)) = 0.46 / 0.91.

All results are stored in data/tda/baseline_experiments.db (NEW database;
nothing existing is modified).
"""

from __future__ import annotations

