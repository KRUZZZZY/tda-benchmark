import numpy as np

PROJECT_ROOT = Path(__file__).parent.parent.parent.parent  # AI_KOS_PROJECT
REPO = Path(__file__).parent.parent                         # projects/tda-benchmark
DATA = PROJECT_ROOT / "data" / "tda"
VENV_PY = PROJECT_ROOT / ".venv-tda" / "bin" / "python"

# ── importlib shim so tda_benchmark factories are reused (same components) ──
spec = importlib.util.spec_from_file_location(
    "tda_benchmark", REPO / "__init__.py", submodule_search_locations=[str(REPO)]
)
pkg = importlib.util.module_from_spec(spec)
sys.modules["tda_benchmark"] = pkg
spec.loader.exec_module(pkg)
from tda_benchmark.factories import ClassifierFactory, FiltrationFactory, VectorizationFactory  # noqa: E402

from sklearn.ensemble import RandomForestClassifier  # noqa: E402
from sklearn.linear_model import LogisticRegression  # noqa: E402
from sklearn.model_selection import StratifiedKFold, cross_val_score  # noqa: E402

CV_SEED = 43  # sweep: random_state = random_seed(42) + repetition(1)

DB_PATH = DATA / "baseline_experiments.db"


def cv_accuracy(X, y, estimator, seed: int = CV_SEED) -> list[float]:
    """Mean-per-fold accuracy under the sweep's exact CV protocol."""
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=seed)
    scores = cross_val_score(estimator, X, y, cv=cv, scoring="accuracy", n_jobs=1)
    return [float(s) for s in scores]


def store_baseline(con, experiment, dataset, feature_type, classifier, sigma,
                   folds, notes=""):
    con.execute(
        """CREATE TABLE IF NOT EXISTS baselines (
               experiment TEXT, dataset TEXT, feature_type TEXT, classifier TEXT,
               sigma REAL, mean_acc REAL, folds TEXT, notes TEXT)"""
    )
    mean = float(np.mean(folds))
    con.execute(
        "INSERT INTO baselines VALUES (?,?,?,?,?,?,?,?)",
        (experiment, dataset, feature_type, classifier, sigma, mean,
         json.dumps(folds), notes),
    )


def store_matched_tda(con, filtration, vectorizer, classifier, sigma, folds):
    con.execute(
        """CREATE TABLE IF NOT EXISTS matched_tda (
               filtration TEXT, vectorizer TEXT, classifier TEXT,
               sigma REAL, mean_acc REAL, folds TEXT)"""
    )
    con.execute(
        "INSERT INTO matched_tda VALUES (?,?,?,?,?,?)",
        (filtration, vectorizer, classifier, sigma, float(np.mean(folds)),
         json.dumps(folds)),
    )


def store_bottleneck(con, dataset, cloud_idx, dim, sigma, d_b, bound):
    con.execute(
        """CREATE TABLE IF NOT EXISTS bottleneck (
               dataset TEXT, cloud_idx INT, dim INT, sigma REAL,
               d_b REAL, bound REAL)"""
    )
    con.execute("INSERT INTO bottleneck VALUES (?,?,?,?,?,?)",
                (dataset, cloud_idx, dim, sigma, d_b, bound))


# ═══════════════════════════════════════════════════════════════════════════
#  Part A — non-topological baselines
# ═══════════════════════════════════════════════════════════════════════════

def part_a(con) -> dict:
    results = {}
    t0 = time.perf_counter()

    # ── MNIST 0/1 ──────────────────────────────────────────────────────────
    X = np.load(DATA / "images" / "mnist_01_X.npy").reshape(400, -1)
    y = np.load(DATA / "images" / "mnist_01_y.npy")
    for name, est in [
        ("logistic", LogisticRegression(max_iter=1000, random_state=42)),
        ("random_forest", RandomForestClassifier(n_estimators=100, random_state=42)),
    ]:
        folds = cv_accuracy(X, y, est)
        store_baseline(con, "A", "mnist_01", "raw_pixels_784", name, None, folds)
        results[f"mnist_raw_{name}"] = folds
        print(f"  MNIST raw-pixels {name:<14} {np.mean(folds)*100:6.2f}%  {folds}")

    # ── ECG200 ─────────────────────────────────────────────────────────────
    X = np.load(DATA / "ucr" / "ecg200_X.npy")
    y = (np.load(DATA / "ucr" / "ecg200_y.npy") > 0).astype(int)
    for name, est in [
        ("logistic", LogisticRegression(max_iter=1000, random_state=42)),
        ("random_forest", RandomForestClassifier(n_estimators=100, random_state=42)),
    ]:
        folds = cv_accuracy(X, y, est)
        store_baseline(con, "A", "ecg200", "raw_signal_96", name, None, folds)
        results[f"ecg_raw_{name}"] = folds
        print(f"  ECG200 raw-signal {name:<14} {np.mean(folds)*100:6.2f}%  {folds}")
    ssq = (X ** 2).sum(axis=1)
    amp = X.max(axis=1) - X.min(axis=1)
    for label, F in [
        ("sum_of_squares", ssq.reshape(-1, 1)),
        ("amplitude", amp.reshape(-1, 1)),
        ("sum_of_squares+amplitude", np.c_[ssq, amp]),
    ]:
        folds = cv_accuracy(F, y, LogisticRegression(max_iter=2000, random_state=42))
        store_baseline(con, "A", "ecg200", label, "logistic", None, folds)
        results[f"ecg_{label}"] = folds
        print(f"  ECG200 {label:<24} {np.mean(folds)*100:6.2f}%  {folds}")

    # ── sphere/torus per noise level ───────────────────────────────────────
    for sigma in (0.00, 0.05, 0.15, 0.30):
        tag = f"noise{int(sigma * 100)}"
        X = np.load(DATA / "synthetic" / f"sphere_torus_{tag}_X.npy")
        y = np.load(DATA / "synthetic" / f"sphere_torus_{tag}_y.npy")
        norms = np.linalg.norm(X, axis=2)
        F_norm = np.stack([norms.mean(1), norms.max(1), norms.min(1)], axis=1)
        folds = cv_accuracy(F_norm, y, LogisticRegression(max_iter=1000, random_state=42))
        store_baseline(con, "A", f"sphere_torus_n{int(sigma*100)}", "norm_feats_3",
                       "logistic", sigma, folds)
        results[f"st_norm_{tag}"] = folds
        print(f"  sphere/torus σ={sigma:.2f} norm-feats logistic   {np.mean(folds)*100:6.2f}%  {folds}")
        folds = cv_accuracy(X.reshape(len(X), -1), y,
                            LogisticRegression(max_iter=1000, random_state=42))
        store_baseline(con, "A", f"sphere_torus_n{int(sigma*100)}", "raw_coords_300",
                       "logistic", sigma, folds)
        results[f"st_raw_{tag}"] = folds
        print(f"  sphere/torus σ={sigma:.2f} raw-coords logistic    {np.mean(folds)*100:6.2f}%  {folds}")
        if sigma in (0.00, 0.30):
            rule = (norms.max(axis=1) > 1.1).astype(int)
            acc = float((rule == y).mean())
            store_baseline(con, "A", f"sphere_torus_n{int(sigma*100)}", "hand_rule_norm>1.1",
                           "hand_rule", sigma, [acc] * 5, notes="whole-dataset accuracy (no CV)")
            results[f"st_handrule_{tag}"] = [acc] * 5
            print(f"  sphere/torus σ={sigma:.2f} hand rule (any norm>1.1) {acc*100:6.2f}%")

    print(f"  [part A done in {time.perf_counter()-t0:.1f}s]")
    return results


# ═══════════════════════════════════════════════════════════════════════════
#  Part B — matched synthetic: baselines + TDA subset
# ═══════════════════════════════════════════════════════════════════════════

def _run_one_matched_tda(fil: str, vec: str, clf: str, sigma: float,
                         matched_dir: str) -> tuple:
    """One matched-synthetic TDA config under the sweep's 5-fold CV.

    Module-level so loky can pickle it; builds components directly (identical
    kwargs to tda_benchmark.factories) so workers need no package shim."""
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.linear_model import LogisticRegression
    from sklearn.pipeline import Pipeline
    from sklearn.preprocessing import FunctionTransformer
    from sklearn.svm import SVC
    from gtda.diagrams import BettiCurve, PersistenceImage, PersistenceLandscape
    from gtda.homology import VietorisRipsPersistence, WeakAlphaPersistence

    _FLATTEN = FunctionTransformer(
        lambda x: x.reshape(x.shape[0], -1), validate=False)

    tag = f"noise{int(sigma * 100)}"
    X = np.load(os.path.join(matched_dir, f"matched_torus_genus_{tag}_X.npy"))
    y = np.load(os.path.join(matched_dir, f"matched_torus_genus_{tag}_y.npy"))

    if fil == "vietoris_rips":
        filtration = VietorisRipsPersistence(homology_dimensions=(0, 1), n_jobs=1)
    else:  # weak_alpha
        filtration = WeakAlphaPersistence(homology_dimensions=(0, 1), n_jobs=1)

    if vec == "persistence_image":
        vectorizer = Pipeline([("vec", PersistenceImage(sigma=0.1, n_bins=20, n_jobs=1)),
                               ("flatten", _FLATTEN)])
    elif vec == "betti_curve":
        vectorizer = Pipeline([("vec", BettiCurve(n_bins=50, n_jobs=1)),
                               ("flatten", _FLATTEN)])
    else:  # persistence_landscape
        vectorizer = Pipeline([("vec", PersistenceLandscape(n_bins=50, n_layers=3, n_jobs=1)),
                               ("flatten", _FLATTEN)])

    if clf == "svm_rbf":
        classifier = SVC(kernel="rbf", C=1.0, gamma="scale", random_state=42)
    else:  # random_forest
        classifier = RandomForestClassifier(n_estimators=100, random_state=42)

    pipeline = Pipeline([("filtration", filtration),
                         ("vectorizer", vectorizer),
                         ("classifier", classifier)])
    folds = cv_accuracy(X, y, pipeline)
    return fil, vec, clf, sigma, folds


def part_b(con) -> dict:
    results = {}
    t0 = time.perf_counter()
    from joblib import Parallel, delayed

    matched_dir = str(DATA / "synthetic_matched")

    for sigma in (0.00, 0.30):
        tag = f"noise{int(sigma * 100)}"
        X = np.load(os.path.join(matched_dir, f"matched_torus_genus_{tag}_X.npy"))
        y = np.load(os.path.join(matched_dir, f"matched_torus_genus_{tag}_y.npy"))
        norms = np.linalg.norm(X, axis=2)
        F_norm = np.stack([norms.mean(1), norms.max(1), norms.min(1)], axis=1)
        folds = cv_accuracy(F_norm, y, LogisticRegression(max_iter=1000, random_state=42))
        store_baseline(con, "B", "matched_torus_genus", "norm_feats_3", "logistic",
                       sigma, folds)
        results[f"matched_norm_{tag}"] = folds
        print(f"  matched σ={sigma:.2f} norm-feats logistic   {np.mean(folds)*100:6.2f}%  {folds}")
        folds = cv_accuracy(X.reshape(len(X), -1), y,
                            LogisticRegression(max_iter=2000, random_state=42))
        store_baseline(con, "B", "matched_torus_genus", "raw_coords_600", "logistic",
                       sigma, folds)
        results[f"matched_raw_{tag}"] = folds
        print(f"  matched σ={sigma:.2f} raw-coords logistic    {np.mean(folds)*100:6.2f}%  {folds}")

    # ── TDA subset: 2 filtrations x 3 vectorizers x 2 classifiers ─────────
    configs = []
    for fil in ("vietoris_rips", "weak_alpha"):
        for vec in ("persistence_image", "betti_curve", "persistence_landscape"):
            for clf in ("svm_rbf", "random_forest"):
                configs.append((fil, vec, clf))
    jobs = [(fil, vec, clf, sigma)
            for sigma in (0.00, 0.30) for (fil, vec, clf) in configs]

    def run_one(job):
        fil, vec, clf, sigma = job
        tag = f"noise{int(sigma * 100)}"
        X = np.load(matched_dir / f"matched_torus_genus_{tag}_X.npy")
        y = np.load(matched_dir / f"matched_torus_genus_{tag}_y.npy")
        pipeline = Pipeline([
            ("filtration", FiltrationFactory.create(fil, homology_dimensions=(0, 1))),
            ("vectorizer", VectorizationFactory.create(vec)),
            ("classifier", ClassifierFactory.create(clf)),
        ])
        folds = cv_accuracy(X, y, pipeline)
        return fil, vec, clf, sigma, folds

    n_workers = min(8, os.cpu_count() or 4)
    print(f"  running {len(jobs)} TDA configs on {n_workers} workers ...")
    out = Parallel(n_jobs=n_workers, backend="loky", verbose=5)(
        delayed(_run_one_matched_tda)(fil, vec, clf, sigma, matched_dir)
        for (fil, vec, clf, sigma) in jobs
    )
    for fil, vec, clf, sigma, folds in out:
        store_matched_tda(con, fil, vec, clf, sigma, folds)
        results[f"tda_{fil}_{vec}_{clf}_{sigma}"] = folds
        print(f"  matched σ={sigma:.2f} {fil:<14} {vec:<22} {clf:<12} {np.mean(folds)*100:6.2f}%  {folds}")
    print(f"  [part B done in {time.perf_counter()-t0:.1f}s]")
    return results


# ═══════════════════════════════════════════════════════════════════════════
#  Part C — measured bottleneck distances vs the paper's bound
# ═══════════════════════════════════════════════════════════════════════════

def part_c(con) -> dict:
    results = {}
    t0 = time.perf_counter()
    import ripser
    import gudhi.bottleneck as gb

    X = np.load(DATA / "synthetic" / "sphere_torus_noise0_X.npy")
    y = np.load(DATA / "synthetic" / "sphere_torus_noise0_y.npy")
    n = X.shape[1]
    sigmas = [0.15, 0.30]
    bounds = {0.15: 0.46, 0.30: 0.91}  # paper: O(sigma sqrt(2 log n)), n=100

    idx = {0: np.where(y == 0)[0][:10], 1: np.where(y == 1)[0][:10]}
    names = {0: "sphere", 1: "torus"}
    rng = np.random.default_rng(2024)

    for cls in (0, 1):
        for sigma in sigmas:
            dbs = {0: [], 1: []}
            for i in idx[cls]:
                clean = X[i]
                noisy = clean + rng.normal(0.0, sigma, clean.shape)
                dg_c = ripser.ripser(clean, maxdim=1)["dgms"]
                dg_n = ripser.ripser(noisy, maxdim=1)["dgms"]
                for dim in (0, 1):
                    d1 = dg_c[dim][dg_c[dim][:, 1] - dg_c[dim][:, 0] > 0]
                    d2 = dg_n[dim][dg_n[dim][:, 1] - dg_n[dim][:, 0] > 0]
                    db = gb.bottleneck_distance(d1, d2)
                    dbs[dim].append(db)
                    store_bottleneck(con, names[cls], int(i), dim, sigma, db,
                                     bounds[sigma])
            for dim in (0, 1):
                mean_db = float(np.mean(dbs[dim]))
                max_db = float(np.max(dbs[dim]))
                results[f"db_{names[cls]}_H{dim}_{sigma}"] = (mean_db, max_db, bounds[sigma])
                print(f"  {names[cls]:6s} σ={sigma:.2f} H{dim}: d_B mean {mean_db:.4f} "
                      f"max {max_db:.4f}  vs bound {bounds[sigma]}")

    # paper's comparison basis: H1 persistence range of clean torus (top-2)
    pers = []
    for i in idx[1]:
        dgm = ripser.ripser(X[i], maxdim=1)["dgms"][1]
        p = np.sort(dgm[:, 1] - dgm[:, 0])[::-1][:2]
        pers.extend(p.tolist())
    results["torus_H1_persistence_range"] = (float(min(pers)), float(max(pers)))
    print(f"  clean torus top-2 H1 persistence range: [{min(pers):.3f}, {max(pers):.3f}]")
    print(f"  [part C done in {time.perf_counter()-t0:.1f}s]")
    return results


def main() -> None:
    con = sqlite3.connect(DB_PATH)
    for table in ("baselines", "matched_tda", "bottleneck"):
        con.execute(f"DROP TABLE IF EXISTS {table}")
    con.commit()

    print("=== Part A: non-topological baselines ===")
    part_a(con)
    print("\n=== Part B: matched synthetic (genus-1 vs genus-2) ===")
    part_b(con)
    print("\n=== Part C: bottleneck distances clean vs noisy ===")
    part_c(con)

    con.commit()
    con.close()
    print(f"\nAll results stored in {DB_PATH}")


if __name__ == "__main__":
    main()
